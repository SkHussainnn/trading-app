// Generate synthetic chart data for any coin and days
export function generateMockChartData(basePrice = 65000, days = 7) {
  const points = days === 1 ? 24 : days === 7 ? 40 : days === 30 ? 60 : 90;
  const prices = [];
  let current = basePrice * 0.94;
  const now = Date.now();
  const step = (days * 24 * 3600 * 1000) / points;

  for (let i = 0; i <= points; i++) {
    const timestamp = now - (points - i) * step;
    const variation = (Math.random() - 0.48) * 0.03 * current;
    current = Math.max(current + variation, basePrice * 0.6);
    prices.push([timestamp, Number(current.toFixed(2))]);
  }

  // Ensure last price is close to basePrice
  prices[prices.length - 1][1] = basePrice;

  return { prices };
}
